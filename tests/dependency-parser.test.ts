import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import {
  parseDependencyFiles,
  parseNpmDependencies,
  parseYarnLockDependencies,
  SUPPORTED_ECOSYSTEMS,
} from "../src/lib/dependency-parser";

test("parseNpmDependencies extracts nested package-lock dependency names correctly", () => {
  const dependencies = parseNpmDependencies(
    JSON.stringify({ dependencies: { "@types/node": "^20.11.30" } }),
    "packages/web/package.json",
    JSON.stringify({
      packages: {
        "": { version: "1.0.0" },
        "node_modules/foo": { version: "1.0.0" },
        "node_modules/foo/node_modules/@types/node": { version: "20.11.30", dev: true },
      },
    }),
    "packages/web/package-lock.json"
  );

  assert.equal(dependencies.some((dependency) => dependency.name === "foo/node_modules/@types/node"), false);
  assert.deepEqual(
    dependencies.find((dependency) => dependency.name === "@types/node"),
    {
      name: "@types/node",
      version: "20.11.30",
      ecosystem: "npm",
      isDev: true,
      manifestPath: "packages/web/package.json",
      lockfilePath: "packages/web/package-lock.json",
      sourceDirectory: "packages/web",
    }
  );
});

test("parseDependencyFiles preserves duplicate dependencies across manifest locations", () => {
  const result = parseDependencyFiles([
    {
      path: "package.json",
      content: JSON.stringify({ dependencies: { react: "19.2.3" } }),
    },
    {
      path: "packages/admin/package.json",
      content: JSON.stringify({ dependencies: { react: "19.2.3" } }),
    },
  ]);

  assert.equal(result.locationCount, 2);
  assert.equal(result.dependencies.length, 2);
  assert.deepEqual(
    result.dependencies.map((dependency) => dependency.manifestPath).sort(),
    ["package.json", "packages/admin/package.json"]
  );
});

test("parseNpmDependencies reports every version of a package found in package-lock", () => {
  const dependencies = parseNpmDependencies(
    JSON.stringify({ dependencies: { lodash: "^4.17.21", "some-lib": "^1.0.0" } }),
    "package.json",
    readFileSync(path.join(process.cwd(), "tests", "fixtures", "package-lock-nested-duplicate.json"), "utf8"),
    "package-lock.json"
  );

  assert.deepEqual(
    dependencies.filter((dependency) => dependency.name === "lodash").map((dependency) => dependency.version).sort(),
    ["4.17.10", "4.17.21"]
  );
  assert.equal(dependencies.filter((dependency) => dependency.name === "some-lib").length, 1);
});

const tuples = (dependencies: { ecosystem: string; name: string; version: string }[]) =>
  dependencies.map((dependency) => `${dependency.ecosystem}:${dependency.name}@${dependency.version}`).sort();

const supportedFiles = () => SUPPORTED_ECOSYSTEMS.flatMap((entry) => entry.files);

const YARN_CLASSIC_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":
  version "7.12.13"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.12.13.tgz"
  dependencies:
    "@babel/highlight" "^7.12.13"

lodash@^4.17.15, lodash@^4.17.20:
  version "4.17.20"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.20.tgz"

lodash@^3.0.0:
  version "3.10.1"
`;

const YARN_BERRY_LOCK = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  checksum: 10c0/abc
  languageName: node
  linkType: hard

"@types/node@npm:^20.0.0, @types/node@npm:^20.11.0":
  version: 20.11.30
  resolution: "@types/node@npm:20.11.30"

"my-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "my-app@workspace:."
  languageName: unknown
  linkType: soft
`;

test("parseYarnLockDependencies reads classic yarn.lock entries", () => {
  assert.deepEqual(tuples(parseYarnLockDependencies(YARN_CLASSIC_LOCK, "package.json", "yarn.lock")), [
    "npm:@babel/code-frame@7.12.13",
    "npm:lodash@3.10.1",
    "npm:lodash@4.17.20",
  ]);
});

test("parseYarnLockDependencies reads berry yarn.lock entries and skips workspaces", () => {
  assert.deepEqual(tuples(parseYarnLockDependencies(YARN_BERRY_LOCK, undefined, "yarn.lock")), [
    "npm:@types/node@20.11.30",
    "npm:lodash@4.17.21",
  ]);
});

test("parseDependencyFiles prefers yarn.lock versions over package.json ranges in subdirectories", () => {
  const result = parseDependencyFiles([
    { path: "apps/web/package.json", content: JSON.stringify({ dependencies: { lodash: "^4.17.15" } }) },
    { path: "apps/web/yarn.lock", content: YARN_CLASSIC_LOCK },
  ]);

  const lodash = result.dependencies.filter((dependency) => dependency.name === "lodash");
  assert.deepEqual(lodash.map((dependency) => dependency.version).sort(), ["3.10.1", "4.17.20"]);
  assert.equal(lodash[0].lockfilePath, "apps/web/yarn.lock");
  assert.equal(lodash[0].manifestPath, "apps/web/package.json");
  assert.ok(supportedFiles().includes("yarn.lock"));
});
