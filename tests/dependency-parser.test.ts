test("parseRequirementsTxtDependencies reads pinned entries and skips the rest", () => {
  assert.deepEqual(tuples(parseRequirementsTxtDependencies(REQUIREMENTS_TXT, "requirements.txt")), [
    "PyPI:Django@4.2.1",
    "PyPI:pyyaml@6.0.1",
    "PyPI:requests@2.31.0",
    "PyPI:urllib3@2.0.7",
  ]);
});

test("parsePythonLockDependencies reads poetry.lock and uv.lock registry packages", () => {
  assert.deepEqual(tuples(parsePythonLockDependencies(POETRY_LOCK, "poetry.lock")), [
    "PyPI:certifi@2023.7.22",
    "PyPI:django@4.2.1",
  ]);
  assert.deepEqual(tuples(parsePythonLockDependencies(UV_LOCK, "uv.lock")), ["PyPI:requests@2.31.0"]);
});

test("parseDependencyFiles prefers Python lockfile versions over requirements.txt in subdirectories", () => {
  const result = parseDependencyFiles([
    { path: "services/api/requirements.txt", content: "Django==4.0.0\nrich==13.7.0\n" },
    { path: "services/api/poetry.lock", content: POETRY_LOCK },
  ]);

  assert.deepEqual(tuples(result.dependencies), [
    "PyPI:certifi@2023.7.22",
    "PyPI:django@4.2.1",
    "PyPI:rich@13.7.0",
  ]);
  assert.equal(result.dependencies.find((dependency) => dependency.name === "django")?.lockfilePath, "services/api/poetry.lock");
  assert.ok(["requirements.txt", "poetry.lock", "uv.lock"].every((file) => supportedFiles().includes(file)));
});
